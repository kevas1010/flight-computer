#!/usr/bin/env python3
"""Side-by-side comparison of every measurement set in results/.

Each results/<set>/ directory is a permanent record written by scripts/measure.sh
(machine.txt + per-run JSON). This script only reads them, so adding a new
machine (e.g. a Raspberry Pi) adds rows and never replaces earlier ones.

    python3 scripts/compare.py                  # print the Markdown table
    python3 scripts/compare.py --update-readme  # also rewrite the table in README.md
"""

from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "<!-- COMPARISON:BEGIN (generated by scripts/compare.py; do not edit by hand) -->"
END = "<!-- COMPARISON:END -->"
CONFIGS = [
    ("timing_default_", "default scheduler"),
    ("timing_rt_", "SCHED_FIFO"),
    ("timing_rt_spin_", "SCHED_FIFO + 500 µs spin"),
]


def load_json(p: Path) -> dict | None:
    try:
        return json.loads(p.read_text())
    except (OSError, json.JSONDecodeError):
        return None


def machine_info(d: Path) -> dict[str, str]:
    info: dict[str, str] = {}
    try:
        for line in (d / "machine.txt").read_text().splitlines():
            key, _, value = line.partition(":")
            info[key.strip()] = value.strip()
    except OSError:
        pass
    return info


def label(d: Path, info: dict[str, str]) -> str:
    platform = "WSL2 (VM)" if "WSL2" in info.get("platform", "") else "bare metal"
    cpu = info.get("cpu", "unknown CPU")
    return f"{platform}: {cpu}"


def timing_runs(d: Path, prefix: str) -> list[dict]:
    runs = []
    for run in sorted(d.glob(f"{prefix}*")):
        # timing_rt_ must not swallow timing_rt_spin_ runs.
        if prefix == "timing_rt_" and run.name.startswith("timing_rt_spin_"):
            continue
        s = load_json(run / "fc_stats.json")
        if s:
            runs.append(s)
    return runs


def fmt(x: float) -> str:
    return f"{x:.0f}" if x >= 10 else f"{x:.1f}"


def build_table(results: Path) -> str:
    sets = sorted(d for d in results.iterdir() if d.is_dir() and (d / "machine.txt").exists())
    if not sets:
        return "_No result sets in results/ yet._"

    lines = [
        "| result set | machine | configuration | runs | frames | period jitter p50 / p99 (µs) | wake latency p50 / p99 (µs) | worst frame (µs) | overruns |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for d in sets:
        info = machine_info(d)
        for prefix, name in CONFIGS:
            runs = timing_runs(d, prefix)
            if not runs:
                continue
            j50 = statistics.median(r["period_jitter"]["p50_us"] for r in runs)
            j99 = statistics.median(r["period_jitter"]["p99_us"] for r in runs)
            w50 = statistics.median(r["wake_latency"]["p50_us"] for r in runs)
            w99 = statistics.median(r["wake_latency"]["p99_us"] for r in runs)
            worst = max(max(r["period_jitter"]["max_us"], r["wake_latency"]["max_us"]) for r in runs)
            frames = sum(r["wake_latency"]["count"] for r in runs)
            overruns = sum(r["overruns"] for r in runs)
            lines.append(
                f"| [{d.name}](results/{d.name}/summary.md) | {label(d, info)} | {name} | {len(runs)} | {frames} "
                f"| {fmt(j50)} / {fmt(j99)} | {fmt(w50)} / {fmt(w99)} | {fmt(worst)} | {overruns} |"
            )

    lines += [
        "",
        "| result set | uplink under 20 % loss | uplink under 20 % loss + 1 % corruption | telemetry delivered under 20 % loss |",
        "|---|---|---|---|",
    ]
    for d in sets:
        def uplink(name: str) -> str:
            s = load_json(d / f"{name}.json")
            if not s:
                return "–"
            lat = s.get("latency_ms") or {}
            return f"{s['acked']}/{s['commands']} ({s['delivery_pct']} %), p99 {lat.get('p99')} ms"

        tlm = load_json(d / "netem20_flight" / "gs_stats.json")
        tlm_s = f"{tlm['telemetry']['delivery_pct']} %" if tlm else "–"
        lines.append(f"| {d.name} | {uplink('uplink_netem20')} | {uplink('uplink_netem20_corrupt1')} | {tlm_s} |")

    lines.append("")
    lines.append("Medians across each configuration's flights; *worst frame* is the single worst "
                 "frame over all of them. Every set keeps its full raw data in `results/<set>/`.")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", type=Path, default=ROOT / "results")
    ap.add_argument("--update-readme", action="store_true")
    args = ap.parse_args()

    table = build_table(args.results)
    print(table)
    if args.update_readme:
        readme = ROOT / "README.md"
        text = readme.read_text()
        if BEGIN not in text or END not in text:
            raise SystemExit("README.md has no comparison markers")
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        readme.write_text(f"{head}{BEGIN}\n{table}\n{END}{tail}")
        print("\nREADME.md comparison table updated")


if __name__ == "__main__":
    main()
